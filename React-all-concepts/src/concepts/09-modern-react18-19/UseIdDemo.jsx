import React, { useId } from 'react';
import SectionCard from '../../components/ui/SectionCard';

function AccessibleFormField({ label, hint, placeholder }) {
  // useId generates a unique, stable string guaranteed not to clash
  const id = useId();
  const hintId = `${id}-hint`;

  return (
    <div style={{ display: 'flex', flexDirection: 'column', gap: '0.3rem' }}>
      <label htmlFor={id} style={{ fontSize: '0.85rem', color: '#cbd5e1', fontWeight: 600 }}>
        {label}
      </label>
      <input
        id={id}
        aria-describedby={hintId}
        type="text"
        placeholder={placeholder}
        className="input-field"
      />
      <small id={hintId} style={{ color: '#64748b', fontSize: '0.75rem' }}>
        {hint} (Generated ID: <code style={{ color: '#38bdf8' }}>{id}</code>)
      </small>
    </div>
  );
}

